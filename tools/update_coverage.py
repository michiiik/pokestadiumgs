#!/usr/bin/env python3
"""Generate COVERAGE.md, the decompilation coverage snapshot.

Historically this script ran as a post-commit hook and rewrote README.md
*after* each commit, which meant the published number always lagged the
commit that produced it by one. It now runs as a pre-commit step
(``.githooks/pre-commit.d/10-coverage.sh``): it regenerates ``COVERAGE.md``
from the staged tree and the hook ``git add``s the result, so the coverage
snapshot lands in the same commit it describes.

Usage:

    python3 tools/update_coverage.py                  # HEAD
    python3 tools/update_coverage.py --revision abc123 # a specific commit
    python3 tools/update_coverage.py --staged          # the git index

The script is also usable as a library (see ``coverage_snapshot`` and
``render_coverage_md``) for tests and other tooling.
"""

from __future__ import annotations

import argparse
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path


BASELINE_COMMIT = "f477acf"
BASELINE_TOTAL = 10_532
START_MARKER = "<!-- AUTO_COVERAGE:START -->"
END_MARKER = "<!-- AUTO_COVERAGE:END -->"
GENERATED_HEADER = (
    "<!-- Generated by tools/update_coverage.py. Do not edit by hand. -->"
)
PRAGMA_PATTERN = r'GLOBAL_ASM\("asm/us/nonmatchings/[^" ]+/[^"/]+\.s"\)'
PRAGMA_RE = re.compile(
    r'GLOBAL_ASM\("asm/us/nonmatchings/[^" ]+/([^"/]+)\.s"\)'
)


def _git_grep_stdout(repo_root: Path, revision: str, staged: bool) -> str:
    cmd = ["git", "-C", str(repo_root), "grep", "--no-color"]
    if staged:
        cmd.append("--cached")
    cmd += ["-E", PRAGMA_PATTERN]
    if not staged:
        cmd.append(revision)
    cmd += ["--", "disasm/src"]
    result = subprocess.run(cmd, check=False, capture_output=True, text=True)
    if result.returncode not in (0, 1):
        raise RuntimeError(result.stderr.strip() or f"git grep failed: {result.returncode}")
    return result.stdout


def _owners_by_file(repo_root: Path, revision: str, staged: bool) -> dict[str, set[str]]:
    """Return ``{source_path: {owner_names}}`` for remaining GLOBAL_ASM pragmas.

    ``staged`` inspects the git index (the tree that would be committed);
    otherwise ``revision`` (a commit-ish, default ``HEAD``) is inspected via
    ``git grep <revision>``. Both modes read git's tracked content, never the
    working tree, so uncommitted-but-unstaged edits never affect the count.
    """

    stdout = _git_grep_stdout(repo_root, revision, staged)
    prefix = "" if staged else f"{revision}:"
    owners: dict[str, set[str]] = {}
    for line in stdout.splitlines():
        text = line[len(prefix):] if prefix and line.startswith(prefix) else line
        path, sep, content = text.partition(":")
        if not sep:
            continue
        match = PRAGMA_RE.search(content)
        if not match:
            continue
        owners.setdefault(path, set()).add(match.group(1))
    return owners


@dataclass(frozen=True)
class CoverageSnapshot:
    covered: int
    total: int
    percentage: float
    remaining_by_file: dict[str, int]


def coverage_snapshot(
    repo_root: Path, revision: str = "HEAD", staged: bool = False
) -> CoverageSnapshot:
    """Return the coverage snapshot for ``revision`` (or the index if ``staged``)."""

    try:
        owners = _owners_by_file(repo_root, revision, staged)
        remaining_by_file = {path: len(names) for path, names in owners.items()}
        remaining = sum(remaining_by_file.values())
    except RuntimeError:
        # A hook should still be useful in a shallow clone where the
        # requested revision is unavailable. The baseline total is immutable,
        # and per-file detail is simply unavailable in this fallback.
        remaining_by_file = {}
        remaining = BASELINE_TOTAL
    total = BASELINE_TOTAL
    covered = max(total - remaining, 0)
    percentage = (covered / total * 100.0) if total else 0.0
    return CoverageSnapshot(covered, total, percentage, remaining_by_file)


def baseline_remaining_by_file(repo_root: Path) -> dict[str, int] | None:
    """Return per-file owner counts at ``BASELINE_COMMIT``, or ``None`` if unavailable."""

    try:
        owners = _owners_by_file(repo_root, BASELINE_COMMIT, staged=False)
    except RuntimeError:
        return None
    return {path: len(names) for path, names in owners.items()}


def render_block(covered: int, total: int, percentage: float) -> str:
    remaining = total - covered
    return "\n".join(
        [
            START_MARKER,
            "- US functions with C implementations: "
            f"**{covered:,} / {total:,} ({percentage:.1f}%)**",
            f"- Remaining `GLOBAL_ASM` owners: **{remaining:,}**",
            f"- Baseline: `{BASELINE_COMMIT}` (vendored US pragma snapshot)",
            END_MARKER,
        ]
    )


def render_file_table(
    remaining_by_file: dict[str, int], baseline_by_file: dict[str, int] | None
) -> str:
    """Render the per-source-file remaining-owners table.

    Rows cover every source file that currently has at least one remaining
    ``GLOBAL_ASM`` owner. ``total`` is the owner count for that file at
    ``BASELINE_COMMIT``; when the baseline revision is unavailable (shallow
    clone) or the file is new since the baseline, ``total`` falls back to the
    current remaining count (0% complete), matching the flat-total fallback
    in ``coverage_snapshot``.
    """

    if not remaining_by_file:
        return "_No source files with remaining `GLOBAL_ASM` owners._"

    lines = [
        "| File | Remaining | Baseline total | Percent complete |",
        "| --- | ---: | ---: | ---: |",
    ]
    for path in sorted(remaining_by_file):
        remaining = remaining_by_file[path]
        if baseline_by_file is not None:
            total = baseline_by_file.get(path, remaining)
        else:
            total = remaining
        covered = max(total - remaining, 0)
        percentage = (covered / total * 100.0) if total else 0.0
        lines.append(f"| `{path}` | {remaining:,} | {total:,} | {percentage:.1f}% |")
    return "\n".join(lines)


def render_coverage_md(snapshot: CoverageSnapshot, baseline_by_file: dict[str, int] | None) -> str:
    block = render_block(snapshot.covered, snapshot.total, snapshot.percentage)
    table = render_file_table(snapshot.remaining_by_file, baseline_by_file)
    return "\n".join(
        [
            GENERATED_HEADER,
            "",
            "# Decompilation coverage",
            "",
            block,
            "",
            "## Remaining owners by source file",
            "",
            table,
            "",
        ]
    )


def write_if_changed(path: Path, content: str) -> bool:
    existing = path.read_text(encoding="utf-8") if path.exists() else None
    if existing == content:
        return False
    path.write_text(content, encoding="utf-8")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=None)
    parser.add_argument(
        "--output", type=Path, default=None, help="Path to write (default: <repo-root>/COVERAGE.md)"
    )
    parser.add_argument(
        "--revision", default="HEAD", help="Git revision to inspect (ignored with --staged)"
    )
    parser.add_argument(
        "--staged",
        action="store_true",
        help="Inspect the git index (staged tree) instead of a revision",
    )
    args = parser.parse_args()

    repo_root = (args.repo_root or Path(__file__).resolve().parent.parent).resolve()
    output = (args.output or repo_root / "COVERAGE.md").resolve()

    snapshot = coverage_snapshot(repo_root, revision=args.revision, staged=args.staged)
    baseline_by_file = baseline_remaining_by_file(repo_root)
    content = render_coverage_md(snapshot, baseline_by_file)
    changed = write_if_changed(output, content)

    print(
        f"coverage: {snapshot.covered}/{snapshot.total} ({snapshot.percentage:.1f}%), "
        f"{snapshot.total - snapshot.covered} GLOBAL_ASM remaining"
        + (" [COVERAGE.md updated]" if changed else " [unchanged]")
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
